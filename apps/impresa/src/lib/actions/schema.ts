export function validateField(field: any) {
  if (!field.key?.trim()) return "La chiave è obbligatoria";
  if (!/^[a-z][a-z0-9_]*$/i.test(field.key.trim()))
    return "Solo lettere, numeri e underscore (deve iniziare con una lettera)";
  if (!DATA_TYPES.includes(field.type)) return "Tipo non valido";
  return null;
}

export function validateAction(action: any) {
  const errors: Record<string, string> = {};
  if (!action.action_id?.trim()) errors.action_id = "Obbligatorio";
  else if (!/^[a-z][a-z0-9_.-]*$/i.test(action.action_id.trim()))
    errors.action_id = "Formato: lettere, numeri, punto, trattino";
  if (!action.name?.trim()) errors.name = "Obbligatorio";
  for (const f of action.inputs || []) {
    const e = validateField(f);
    if (e) { errors.inputs = `Input "${f.key || "(vuota)"}": ${e}`; break; }
  }
  for (const f of action.outputs || []) {
    const e = validateField(f);
    if (e) { errors.outputs = `Output "${f.key || "(vuota)"}": ${e}`; break; }
  }
  return errors;
}

export function emptyField() {
  return { key: "", type: "string", required: false };
}

export function emptyAction() {
  return {
    id: crypto.randomUUID(),
    action_id: "",
    name: "",
    description: "",
    origin: "custom_partner",
    requires_kb: [],
    inputs: [emptyField()],
    outputs: [emptyField()],
    status: "pending",
    updated_at: new Date().toISOString(),
  };
}

