export const actionsStore = {
  getAll: () => [..._actions],
  subscribe(fn: Function) { listeners.add(fn); return () => listeners.delete(fn); },
  emit() { listeners.forEach((fn) => fn([..._actions])); },
  upsert(action: any) {
    const i = _actions.findIndex((a) => a.id === action.id);
    const next = { ...action, updated_at: new Date().toISOString() };
    if (i >= 0) _actions[i] = next; else _actions = [next, ..._actions];
    this.emit();
    return next;
  },
  remove(id: string) { _actions = _actions.filter((a) => a.id !== id); this.emit(); },
};
